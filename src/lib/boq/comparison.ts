/**
 * Line-by-line comparison of what was read from the uploaded file with what is
 * recorded in the system. Pure, so the review screen and its tests share one rule.
 */

export type BOQComparisonLine = {
  itemId: string | null;
  rowNumber: number;
  section: string;
  itemCode: string;
  description: string;
  unit: string;
  quantity: string;
  unitCost: string;
  amount: string;
};

export type ComparisonStatus = 'Matched' | 'Changed' | 'Only in file' | 'Only in system';
export type ComparisonField = 'section' | 'itemCode' | 'description' | 'unit' | 'quantity' | 'unitCost' | 'amount';
export type ComparisonRow = {
  source: BOQComparisonLine | null;
  current: BOQComparisonLine | null;
  status: ComparisonStatus;
  /** Fields whose values differ (only for Changed rows). */
  changed: ComparisonField[];
};

export const decimal = (value: string | number | null | undefined): number => {
  const parsed = Number(value ?? 0);
  return Number.isFinite(parsed) ? parsed : 0;
};
export const isStated = (value: string | undefined | null) => value !== undefined && value !== null && value.trim() !== '';
const sameNumber = (left: string, right: string) => isStated(left) === isStated(right) && Math.abs(decimal(left) - decimal(right)) < 0.005;

/**
 * The importer keeps the file's stated amount as authoritative and, when the stated unit rate does not
 * reproduce it (e.g. the rate column is the base cost before mark-ups/VAT), records the rate derived from
 * the amount. That is reported once as a "Unit rate" reading finding; counting it again as a changed item
 * flagged every line of such files (e.g. 326 of 326) and hid real differences.
 */
function isRateDerivedFromUnchangedAmount(source: BOQComparisonLine, current: BOQComparisonLine) {
  if (!sameNumber(source.quantity, current.quantity)) return false;
  if (Math.abs(decimal(source.amount) - decimal(current.amount)) >= 0.005) return false;
  const quantity = decimal(current.quantity);
  if (!isStated(current.unitCost) || quantity === 0) return false;
  // Stored rates are rounded to centavos, so allow up to half a centavo per unit.
  return Math.abs(decimal(current.unitCost) * quantity - decimal(current.amount)) <= Math.max(0.01, Math.abs(quantity) * 0.005);
}

export function changedFields(source: BOQComparisonLine, current: BOQComparisonLine): ComparisonField[] {
  const fields: ComparisonField[] = [];
  if (source.section.trim() !== current.section.trim()) fields.push('section');
  // A code missing from the file is generated by the system (e.g. ROW-10); that is not a reading difference.
  if (source.itemCode.trim() && source.itemCode.trim() !== current.itemCode.trim()) fields.push('itemCode');
  if (source.description.trim() !== current.description.trim()) fields.push('description');
  if (source.unit.trim() !== current.unit.trim()) fields.push('unit');
  if (!sameNumber(source.quantity, current.quantity)) fields.push('quantity');
  if (!sameNumber(source.unitCost, current.unitCost) && !isRateDerivedFromUnchangedAmount(source, current)) fields.push('unitCost');
  if (Math.abs(decimal(source.amount) - decimal(current.amount)) >= 0.005) fields.push('amount');
  return fields;
}

/** Pair by recorded item id first, then by a unique item code on both sides. */
export function compareBOQLines(sourceRows: BOQComparisonLine[], currentRows: BOQComparisonLine[]): ComparisonRow[] {
  const currentById = new Map(currentRows.filter(row => row.itemId).map(row => [row.itemId!, row]));
  const sourceCodeCount = new Map<string, number>();
  for (const row of sourceRows) if (!row.itemId && row.itemCode.trim()) sourceCodeCount.set(row.itemCode.trim(), (sourceCodeCount.get(row.itemCode.trim()) ?? 0) + 1);
  const usedCurrent = new Set<BOQComparisonLine>();
  const rows: ComparisonRow[] = [];
  for (const source of sourceRows) {
    let current = source.itemId ? currentById.get(source.itemId) : undefined;
    if (!current && source.itemCode.trim()) {
      const code = source.itemCode.trim();
      const candidates = currentRows.filter(row => row.itemCode.trim() === code);
      if (candidates.length === 1 && sourceCodeCount.get(code) === 1) current = candidates[0];
    }
    if (current && !usedCurrent.has(current)) {
      usedCurrent.add(current);
      const changed = changedFields(source, current);
      rows.push({ source, current, status: changed.length ? 'Changed' : 'Matched', changed });
    } else {
      rows.push({ source, current: null, status: 'Only in file', changed: [] });
    }
  }
  for (const current of currentRows) if (!usedCurrent.has(current)) rows.push({ source: null, current, status: 'Only in system', changed: [] });
  return rows;
}

export type SectionComparison = { section: string; sourceAmount: number; currentAmount: number; sourceCount: number; currentCount: number; differences: number };

export function summarizeComparison(rows: ComparisonRow[]) {
  const count = (status: ComparisonStatus) => rows.filter(row => row.status === status).length;
  const sourceTotal = rows.reduce((sum, row) => sum + (row.source ? decimal(row.source.amount) : 0), 0);
  const currentTotal = rows.reduce((sum, row) => sum + (row.current ? decimal(row.current.amount) : 0), 0);
  const sections = new Map<string, SectionComparison>();
  const sectionOf = (row: ComparisonRow) => (row.current?.section || row.source?.section || 'Unsectioned').trim() || 'Unsectioned';
  for (const row of rows) {
    const key = sectionOf(row);
    const entry = sections.get(key) ?? { section: key, sourceAmount: 0, currentAmount: 0, sourceCount: 0, currentCount: 0, differences: 0 };
    if (row.source) { entry.sourceAmount += decimal(row.source.amount); entry.sourceCount += 1; }
    if (row.current) { entry.currentAmount += decimal(row.current.amount); entry.currentCount += 1; }
    if (row.status !== 'Matched') entry.differences += 1;
    sections.set(key, entry);
  }
  return {
    matched: count('Matched'), changed: count('Changed'), onlyInFile: count('Only in file'), onlyInSystem: count('Only in system'),
    differences: rows.length - count('Matched'),
    sourceTotal, currentTotal, difference: currentTotal - sourceTotal,
    sections: [...sections.values()],
    sectionOf,
  };
}
